enum QuestionLevel { light, mid, deep }

class QuestionData {
  final int id;
  final QuestionLevel level;
  final String question;
  final Map<String, List<String>> personaAnswers;

  const QuestionData({
    required this.id,
    required this.level,
    required this.question,
    required this.personaAnswers,
  });

  List<String> getAnswersFor(String persona) {
    if (personaAnswers.containsKey(persona) && personaAnswers[persona]!.isNotEmpty) {
      return personaAnswers[persona]!;
    }
    // Fallback to supporter or first available persona
    return personaAnswers['supporter'] ?? 
           personaAnswers['wise'] ?? 
           personaAnswers['funny'] ?? 
           ['معاك حق في كل كلمة'];
  }
}

